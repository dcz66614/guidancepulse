/**
 * PreToolUse write gate — P025 GuidancePulse, T005.
 *
 * Source of truth: PROJECT_BOOK.md v1.1.0 §6.4 (write-check
 * algorithm), §6.5 (only native Write/Edit are gated; Bash and
 * external processes are NOT covered), §7.3/§7.4 (WRITE_CHECKED
 * event shape and persistence allowlist), and IMPLEMENTATION_PLAN
 * §6 T005 card (warn / ask / block; Hook failure fails closed in
 * strict mode, `onFailure: "block"`).
 *
 * Spec-reference note (same class of mismatch T002–T004 already
 * recorded for §8.2): the T005 task card cites PROJECT_BOOK §7.2
 * as the contract, but §7.2 in v1.1.0 is the module table and the UI
 * colour/wording section is §8.2, which contains no gate semantics.
 * The gate lives in §6.4; this file follows §6.4 verbatim. No spec
 * file was changed.
 *
 * Pipeline (all reuse, no re-implementation):
 *
 *   1. `adaptHookEvent` (T003) — raw Hook JSON -> sanitised
 *      `WriteCheckRequest`, or `ignored` when the tool is not
 *      Write/Edit, the target is outside the project, or no rule
 *      protects it. A malformed KNOWN event throws AdapterError.
 *   2. `matchRules(config, target, livePhase)` (T004) — the §6.4
 *      rule set for this write in the LIVE phase. The adapter's
 *      rule ids are phase-agnostic (the live phase is not part of
 *      Hook input); this step is the phase refinement. A rule that
 *      is inactive in the live phase does not gate the write.
 *   3. `checkWrite` + `checkWriteAndPersist` (T004/T007) — the
 *      §6.4 per-rule lease check against the persisted leases,
 *      with lazy expiry (cwd / phase / budget mismatch) persisted
 *      atomically with the check.
 *   4. `recordEvent(WRITE_CHECKED)` (T007) — one audit event per
 *      gated rule, carrying only §7.4 fields (guidance id, HMAC
 *      path id, decision, state, timestamp). Raw paths, Prompt,
 *      and tool content never reach the store.
 *   5. `buildHookOutput` (decision.ts) — the Claude Code JSON
 *      output + exit code (DENY -> 2, everything else -> 0).
 *
 * Live context the caller supplies:
 *   - `livePhaseId`: the current phase, owned by the CLI
 *     (`guidancepulse phase set`, T006/T011). It is NOT in Hook
 *     input. `null` means "phase unknown" — `checkWrite` then
 *     fails closed: a FRESH lease can never satisfy §6.2
 *     condition 3 against an unknown phase, so it expires
 *     (PHASE_MISMATCH) instead of passing.
 *   - the live cwd comes from the Hook input itself (`cwd` field);
 *     it is HMACed with the T007 path key and compared against
 *     the cwd at lease issuance (§6.2 condition 4).
 *
 * Fail-closed behaviour (strict mode): ANY error inside the gate
 * — malformed Hook envelope, missing file_path on a gated tool,
 * store failure, audit-write failure — returns DENY with exit
 * code 2 and the error code in the reason, never an allow. A
 * PreToolUse mis-allow is a P1 (PROJECT_BOOK §10); a
 * fail-closed deny is a visible, retryable block. The one
 * exception is the lease snapshot (a determinism aid for
 * T009/T010): if it cannot be computed, the result carries "" —
 * a snapshot failure must never turn an already-decided outcome
 * into a deny.
 *
 * What this file does NOT do:
 *   - It does not spend edit budget: budget is spent only after a
 *     write SUCCEEDS (PostToolUse path, via
 *     `recordSuccessfulWrite` below). Spending it here would let a
 *     blocked or failed write consume budget.
 *   - It does not gate Bash, external processes, or IDE writes
 *     (§6.5): those tools return the no-gate allow.
 *   - It does not read the network, the wall clock (timestamps
 *     come from the Hook input via the adapter), or any file
 *     except through the injected store.
 */

