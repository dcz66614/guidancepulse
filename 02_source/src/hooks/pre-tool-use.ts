/** Error code carried by a fail-closed result (never the raw error). */
export interface PreToolUseFailure {
  code: string;
}

/** What the caller needs to run one PreToolUse gate. */
export interface PreToolUseContext {
  /** Validated guidance config (T002 `parseConfigYaml`). */
  config: GuidanceConfig;
  /** Opened SQLite store (T007 `GuidancePulseStore.open`). */
  store: GuidancePulseStore;
  /** Local path key for HMAC path ids (owned/generated by T007). */
  pathKey: string | Uint8Array;
  /**
   * Current live phase id (CLI-managed). `null` / omitted means
   * "phase unknown" and fails closed (see module doc).
   */
  livePhaseId?: string | null;
  /**
   * Timestamp override for determinism (passed through to the
   * adapter). Defaults to the Hook input's own flow (`new
   * Date().toISOString()` inside the adapter).
   */
  now?: string | (() => string);
}

/** Result of one PreToolUse gate evaluation. */
export interface PreToolUseResult {
  /** Aggregated decision (§6.4: block > ask > warn; all FRESH -> ALLOW). */
  decision: WriteDecision;
  /** Claude Code hook JSON output (stdout payload). */
  hookOutput: PreToolUseHookOutput;
  /** Process exit code: 2 for DENY, 0 otherwise. */
  exitCode: 0 | 2;
  /** Per-rule outcomes, in config order (empty when no gate applied). */
  perRule: RuleCheckResult[];
  /** True when at least one rule gated this write in the live phase. */
  gated: boolean;
  /**
   * Canonical lease snapshot after the check (T004
   * `canonicalLeaseSnapshot` over the persisted leases); "" when it
   * could not be computed. Determinism aid for T009/T010; never
   * part of the decision.
   */
  leaseSnapshot: string;
  /** WRITE_CHECKED audit events recorded (one per gated rule). */
  eventsRecorded: number;
  /** Set only when the gate failed closed on an internal error. */
  error?: PreToolUseFailure;
}

/**
 * Run the PreToolUse gate for one raw Hook JSON value. Never throws:
 * internal errors become a fail-closed DENY result (exit code 2)
 * with the error code in `error` and in the hook reason.
 */
export function handlePreToolUse(
  input: unknown,
  ctx: PreToolUseContext,
): PreToolUseResult {
  const livePhaseId = ctx.livePhaseId ?? null;
  try {
    const adapted: AdapterOutput = adaptHookEvent(input, {
      config: ctx.config,
      pathKey: ctx.pathKey,
      now: ctx.now,
    });
    if (adapted.kind !== "write-check") {
      // Tool not gated (not Write/Edit), target outside the project,
      // or no rule protects the target: no guidance gate, no opinion.
      return {
        decision: "ALLOW",
        hookOutput: buildHookOutput("ALLOW", [], { noGate: true }),
        exitCode: 0,
        perRule: [],
        gated: false,
        leaseSnapshot: safeLeaseSnapshot(ctx.store),
        eventsRecorded: 0,
      };
    }
    const request = adapted.request;

    // §6.4 rule set in the LIVE phase. The adapter's rule ids are
    // phase-agnostic; this is the phase refinement.
    const sanitized = sanitizeHookInput(input);
    const relative = toRelativeTarget(sanitized.toolFilePath, sanitized.cwd);
    if (relative === null) {
      // Defensive: the adapter already returns "ignored" for an
      // outside-project target, so this is unreachable in practice.
      return {
        decision: "ALLOW",
        hookOutput: buildHookOutput("ALLOW", [], { noGate: true }),
        exitCode: 0,
        perRule: [],
        gated: false,
        leaseSnapshot: safeLeaseSnapshot(ctx.store),
        eventsRecorded: 0,
      };
    }
    const rules = matchRules(ctx.config, relative, livePhaseId, {
      // FIX-R5: same Windows-origin detection as the adapter, so the
      // gate and the adapter can never disagree about a target's
      // case: drive-letter / UNC cwd or target => case-insensitive
      // glob matching (NTFS); POSIX stays case-sensitive.
      caseInsensitive:
        isWindowsPath(sanitized.cwd) ||
        (sanitized.toolFilePath !== null && isWindowsPath(sanitized.toolFilePath)),
    });
    if (rules.length === 0) {
      // Every rule matching the target is inactive in the live phase.
      return {
        decision: "ALLOW",
        hookOutput: buildHookOutput("ALLOW", [], { noGate: true }),
        exitCode: 0,
        perRule: [],
        gated: false,
        leaseSnapshot: safeLeaseSnapshot(ctx.store),
        eventsRecorded: 0,
      };
    }

    const cwdPathId = computePathId(sanitized.cwd, ctx.pathKey);
    const check: WriteCheckResult = ctx.store.checkWriteAndPersist(
      {
        sessionScopeId: request.sessionScopeId,
        agentScopeId: request.agentScopeId,
        cwdPathId,
        phaseId: livePhaseId,
        rules: rules.map((rule) => ({ id: rule.id, mode: rule.mode })),
      },
      request.timestampUtc,
    );

    // One WRITE_CHECKED audit event per gated rule (§7.3/§7.4:
    // guidance id, HMAC path id, decision, state, timestamp only).
    // If the audit write fails, fail closed: the decision was
    // computed, but an unrecorded gate outcome must not silently
    // allow a write.
    let eventsRecorded = 0;
    for (const ruleResult of check.perRule) {
      const event: GuidancePulseEvent = {
        type: "WRITE_CHECKED",
        sessionScopeId: request.sessionScopeId,
        agentScopeId: request.agentScopeId,
        guidanceId: ruleResult.guidanceId,
        pathId: request.pathId,
        decision: check.decision,
        state: ruleResult.state,
        timestampUtc: request.timestampUtc,
      };
      ctx.store.recordEvent(event);
      eventsRecorded += 1;
    }

    return {
      decision: check.decision,
      hookOutput: buildHookOutput(check.decision, check.perRule),
      exitCode: hookExitCode(check.decision),
      perRule: check.perRule,
      gated: true,
      leaseSnapshot: safeLeaseSnapshot(ctx.store),
      eventsRecorded,
    };
  } catch (error) {
    return failClosedResult(ctx, error);
  }
}

/**
 * Record the outcome of a gated Write/Edit AFTER it ran (the
 * PostToolUse success path, T006/T012 integration). Delegates to
 * the T004 `recordWriteOutcome` via the T007 store: a SUCCESSFUL
 * write spends one edit from the lease's budget (reaching 0
 * expires it); a FAILED write spends nothing. Returns the lease
 * afterwards, or undefined when there is no FRESH lease to spend
 * from. Kept here — not in the PreToolUse gate — so the gate
 * itself can never spend budget for a write that did not run.
 */
export function recordSuccessfulWrite(
  store: GuidancePulseStore,
  sessionScopeId: string,
  agentScopeId: string,
  guidanceId: string,
  outcome: "success" | "failure" = "success",
  timestampUtc?: string,
): GuidanceLease | undefined {
  return store.recordWriteOutcomeAndPersist(
    sessionScopeId,
    agentScopeId,
    guidanceId,
    outcome,
    timestampUtc,
  );
}

/**
 * Re-exported for callers that need the pure §6.4 check without the
 * Hook envelope (T009 Golden harness, T010 gate): same function the
 * gate uses, no behaviour difference.
 */
export { checkWrite };

/**
 * Resolve a sanitised tool target to a project-relative normalised
 * path. Delegates to the shared `resolveRelativeTargetPath` (the
 * same helper the adapter uses), so the gate and the adapter can
 * never disagree about a target — including Windows drive-letter
 * and UNC absolute paths (FIX-R3) and their case variants (FIX-R5).
 * Absolute targets under the Hook cwd become relative; targets
 * outside the cwd return null (no relative `applies_to` glob can
 * match them); a null target returns null. A drive-relative
 * spelling throws SanitizeError `DRIVE_RELATIVE_PATH` out of the
 * shared resolver and is caught by `handlePreToolUse`'s fail-closed
 * handler (DENY, exit 2) — it never reaches the no-gate ALLOW
 * branch above.
 */
function toRelativeTarget(
  toolFilePath: string | null,
  cwd: string,
): string | null {
  return resolveRelativeTargetPath(toolFilePath, cwd);
}

/** Canonical snapshot of the persisted leases; "" when unavailable. */
function safeLeaseSnapshot(store: GuidancePulseStore): string {
  try {
    const leases = store.listAllLeases();
    const map: LeaseStore = new Map(
      leases.map((lease) => [
        leaseKey(lease.sessionScopeId, lease.agentScopeId, lease.guidanceId),
        lease,
      ]),
    );
    return canonicalLeaseSnapshot(map);
  } catch {
    return "";
  }
}

/** Fail-closed result: DENY, exit code 2, error code only (no raw error). */
function failClosedResult(ctx: PreToolUseContext, error: unknown): PreToolUseResult {
  const code =
    error !== null &&
    typeof error === "object" &&
    "code" in error &&
    typeof (error as { code: unknown }).code === "string"
      ? (error as { code: string }).code
      : "PRE_TOOL_USE_FAILED";
  return {
    decision: "DENY",
    hookOutput: buildHookOutput("DENY", [], { failureCode: code }),
    exitCode: 2,
    perRule: [],
    gated: true,
    leaseSnapshot: safeLeaseSnapshot(ctx.store),
    eventsRecorded: 0,
    error: { code },
  };
}
